"""Render eval/TABLE.md from the committed eval/results/*.json. Nothing in the table is typed by hand."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ORDER = ["template", "base", "large", "tuned"]
LABEL = {"template": "Code template (no model)", "base": "Base Qwen3-8B", "large": "Large Qwen3.5-397B",
         "tuned": "Tuned Qwen3-8B (LoRA)"}


def pct(x: float) -> str:
    return f"{x * 100:.1f}%"


def money(x: float | None) -> str:
    if x is None:
        return "n/a"
    return "$0" if x == 0 else f"${x:.5f}"


def render(results: dict[str, dict]) -> str:
    cols = [s for s in ORDER if s in results]
    n = max((results[s]["test_rows"] for s in cols), default=0)
    head = "| Metric | " + " | ".join(LABEL[s] for s in cols) + " |\n|---|" + "---|" * len(cols) + "\n"
    rows = [
        ("Passed the checker on the first try", lambda m: pct(m["first_try_pass"])),
        ("Reply came from the model (first try or one retry)", lambda m: pct(m["served_by_model"])),
        ("Fell back to the code template", lambda m: pct(m["template_fallback"])),
        ("First draft had an invented number", lambda m: pct(m["invented_number_rate"])),
        ("First draft contradicted the facts (storm / rain)", lambda m: pct(m["contradiction_rate"])),
        ("First draft over 160 septets", lambda m: pct(m["too_long_rate"])),
        ("Required-fact coverage of the first draft", lambda m: pct(m["required_fact_coverage"])),
        ("Reply length, mean septets", lambda m: f"{m['septets_mean']:.0f}"),
        ("Reply length, p95 septets", lambda m: f"{m['septets_p95']:.0f}"),
        ("Latency p50, sequential", lambda m: f"{m['latency_p50_s']:.2f} s"),
        ("Latency p95, sequential", lambda m: f"{m['latency_p95_s']:.2f} s"),
        ("Cost per answer (published Tinker prices)", lambda m: money(m["cost_per_answer_usd"])),
        ("Model errors (timeouts, empty text)", lambda m: str(m["model_errors"])),
    ]
    body = "".join(
        f"| {name} | " + " | ".join(fn(results[s]["metrics"]) for s in cols) + " |\n" for name, fn in rows
    )
    models = "; ".join(f"{LABEL[s]} = `{results[s]['model']}`" for s in cols)
    return (
        "# Eval table\n\n"
        f"Generated by `eval/table.py` from `eval/results/*.json`. Test set: {n} questions in `eval/test.jsonl`, "
        "split by 0.5 degree map cell so no place appears in training. Models: " + models + ".\n\n"
        + head + body + "\n"
        "**What the numbers mean.** The checker verifies length, GSM-7 characters, that every number is a fact or a number "
        "the hiker wrote, that the facts the question needs are stated, and that a storm or rain is not denied or invented. "
        "It does not verify that a qualified claim such as \"no storm by noon\" is right, and it does not judge tone. "
        "A pass is therefore necessary, not sufficient. Latency is measured one request at a time on the first 40 questions; "
        "the other columns come from one concurrent pass over all rows. The large model gets the same short prompt as the base model.\n"
    )


def main() -> None:
    results = {}
    for s in ORDER:
        path = ROOT / "eval" / "results" / f"{s}.json"
        if path.is_file():
            results[s] = json.loads(path.read_text(encoding="utf-8"))
    if not results:
        raise SystemExit("no results in eval/results; run eval/run_eval.py first")
    (ROOT / "eval" / "TABLE.md").write_text(render(results), encoding="utf-8")
    print("wrote eval/TABLE.md with", ", ".join(results))


if __name__ == "__main__":
    main()
